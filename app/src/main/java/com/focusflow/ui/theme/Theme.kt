@Composable
fun FocusFlowTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) FocusFlowDarkColorScheme else FocusFlowLightColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = FocusFlowTypography,
        content = content
    )
}
